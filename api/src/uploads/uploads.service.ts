import {
  BadRequestException,
  Injectable,
  NotFoundException,
} from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync } from 'node:fs';
import { unlink } from 'node:fs/promises';
import { resolve, sep, basename } from 'node:path';
import type { Express } from 'express';

/**
 * Photographs on local disk — FR-6.2 and FR-6.3.
 *
 * **The upload directory comes from `UPLOAD_DIR`** (default `uploads`,
 * relative to the working directory) so Docker can mount a volume over it:
 * `docker-compose.yml` does exactly that, and the images survive a rebuild
 * of the API image, which is the difference between a family archive and a
 * family archive until the next deploy.
 *
 * Two rules hold everywhere in this file, and both are about refusing rather
 * than sanitising:
 *
 * - **A stored filename is generated, never the client's.** `multer` is
 *   given a `filename` callback that writes 16 random bytes plus an
 *   extension *derived from the detected type*. Nothing the caller sent can
 *   become a path, so `../../etc/passwd` has nowhere to go.
 * - **A served filename has to match `^[a-f0-9]{32}\.(jpg|png|webp)$`
 *   before the filesystem is touched.** Every other name is a 404 without a
 *   `stat`, and the extension decides both the content type and whether the
 *   file may be read at all.
 */
@Injectable()
export class UploadsService {
  /** Absolute path of the upload directory; created on first use. */
  readonly directory: string;

  constructor(config: ConfigService) {
    this.directory = resolve(
      process.cwd(),
      config.get<string>('UPLOAD_DIR', 'uploads'),
    );
    mkdirSync(this.directory, { recursive: true });
  }

  /** FR-6.2 — JPEG, PNG and WebP, and nothing else. */
  static readonly types: Record<string, string> = {
    'image/jpeg': '.jpg',
    'image/png': '.png',
    'image/webp': '.webp',
  };

  /** FR-6.2 — 5 MB, stated as bytes so one constant is the whole rule. */
  static readonly maxBytes = 5 * 1024 * 1024;

  /** What a stored file is called: generated bytes, extension from type. */
  static filenameFor(mimetype: string): string {
    const ext = UploadsService.types[mimetype];
    if (ext === undefined) {
      throw new BadRequestException(
        'A photograph must be a JPEG, a PNG or a WebP image.',
      );
    }
    return `${randomHex()}${ext}`;
  }

  /** The one shape a stored filename may have (see the note above). */
  static readonly namePattern = /^[a-f0-9]{32}\.(jpg|png|webp)$/;

  /**
   * Refuses a file that is over FR-6.2's 5 MB and **removes it first**:
   * multer has already written the bytes to disk by the time this runs, and
   * a rejected upload that stays on the volume is a disk-fill with a UI.
   *
   * The size check lives here rather than only in multer's `limits` because
   * multer's own message is the bare `"File too large"` with a 413 — the
   * SRS asks for a *clear* message, and this one states the limit and the
   * file's own size.
   */
  async assertSize(file: Express.Multer.File): Promise<void> {
    if (file.size <= UploadsService.maxBytes) return;
    await this.discard(file.filename);
    const shown = (file.size / (1024 * 1024)).toFixed(1);
    throw new BadRequestException(
      `A photograph may be at most 5 MB — this file is ${shown} MB.`,
    );
  }

  /**
   * Removes a rejected upload.
   *
   * The path is resolved by `pathFor` — the one guard that decides what a
   * path in this service may be — rather than read from `file.path`.
   * Multer builds `file.path` itself, from the destination it was handed and
   * the name this API generated, so the two agree in practice; but `file`
   * *arrives* as request data, being the `@UploadedFile()` argument, and a
   * value taken from it and handed straight to `unlink` is a deletion whose
   * target came from outside. Resolving `file.filename` through `pathFor`
   * states the rule once: only a generated name inside the upload directory
   * is ever a path this service acts on — for reading *and* for deleting.
   *
   * Cleanup never changes the response. Whatever happens here, the caller is
   * about to be told the file was over 5 MB, so a file that has already gone
   * (or a name this API would not have served) is swallowed rather than
   * turned into a 404 in place of the 400.
   */
  private async discard(filename: string): Promise<void> {
    try {
      await unlink(this.pathFor(filename));
    } catch {
      /* Already gone, or never ours to remove. */
    }
  }

  /**
   * Resolves a requested filename to a file inside the upload directory,
   * or throws 404.
   *
   * Two independent rules, and the first one is structural rather than a
   * pattern someone might loosen:
   *
   * - **`basename` first.** Whatever arrived in the URL is reduced to its
   *   last segment before it can name anything, so `..`, a separator and an
   *   absolute path have nowhere to go — the value handed to `resolve` is
   *   the caller's only in the sense that it chose a leaf name.
   * - **Then the shape is checked**, and then the containment check below
   *   (kept although a hex name cannot escape, because it is one comparison
   *   and the difference between "impossible today" and "impossible because
   *   of a regex someone might loosen"), and then existence.
   */
  pathFor(filename: string): string {
    const name = basename(filename);
    if (!UploadsService.namePattern.test(name)) {
      throw new NotFoundException('That photograph does not exist.');
    }
    const path = resolve(this.directory, name);
    if (!path.startsWith(this.directory + sep)) {
      throw new NotFoundException('That photograph does not exist.');
    }
    if (!existsSync(path)) {
      throw new NotFoundException('That photograph does not exist.');
    }
    return path;
  }

  /** Content type from the extension — never from a header the client sent. */
  static contentTypeFor(filename: string): string {
    if (filename.endsWith('.png')) return 'image/png';
    if (filename.endsWith('.webp')) return 'image/webp';
    return 'image/jpeg';
  }

  /** The URL a DTO stores: what a browser can request, path included. */
  static urlFor(filename: string): string {
    return `/api/uploads/${filename}`;
  }
}

/**
 * Where photographs live, as an absolute path.
 *
 * Exported because `UploadsController`'s storage options are built when the
 * class is declared — before any `ConfigService` is in scope — so the two
 * places that need this path read it from one function rather than from one
 * `ConfigService.get` and one `process.env` that could drift apart.
 */
export function uploadDirectory(): string {
  return resolve(process.cwd(), process.env.UPLOAD_DIR ?? 'uploads');
}

/** 16 bytes of randomness — 32 hex characters, which the pattern expects. */
function randomHex(): string {
  return randomBytes(16).toString('hex');
}
